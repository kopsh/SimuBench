"""What the ScopeAcquisition collaborators ask of the component: the one interface they read it by."""

from __future__ import annotations

from typing import TYPE_CHECKING, Any, ClassVar, Protocol

from ...engine.signal import Signal
from ...engine.stream import (
    FrameRequest,
)

if TYPE_CHECKING:
    from ...engine.instrument import Instrument
    from ...engine.session import Session
    from ...engine.stream import SampleFrame
    from .scope_capture import Capture
    from .scope_recorder import Recorder
    from .scope_run import RunControl
    from .scope_segments import Segments


class AcquisitionHost(Protocol):
    """What the acquisition family's blocks (capture, segments, recorder, run control) read of
    their component. The instrument's own state and services are members here, not an ``owner``
    to reach through (#1724): a block reads a setting by :meth:`get_state`, writes one by
    :meth:`set_state`, formats replies by :meth:`format_number`/:meth:`format_setting` and
    reports moments by :meth:`status_event`; the pending-operation clock is
    :meth:`now_ns`/:meth:`wait_until`/:meth:`opc_query`/:meth:`wait_pending`/:meth:`arm_opc`;
    the front panel shows in :attr:`on_panel`, a warning goes by :meth:`warn`, and the component
    and port wired to a signal input by :meth:`input_source`."""

    def adc_unit(self) -> Any: ...  # ScopeAdc (ty reads a @component class as a variable)
    def arm_opc(self) -> None: ...
    def averages(self) -> int: ...
    def bound_path(self, key: str) -> str | None: ...

    capture: Capture

    def channels(self) -> int: ...
    def decimator_unit(self) -> Any: ...

    defaults: ClassVar[Any]

    def display_signal(self, n: int) -> Signal: ...
    def displayed(self) -> list[int]: ...
    def format_number(self, value: float) -> bytes: ...
    def format_setting(self, path: str) -> bytes: ...
    def get_state(self, path: str) -> Any: ...
    def horizontal(self) -> Any: ...  # ScopeTimebase (ty reads a @component class as a variable)
    def input_frames(self, port: str, request: FrameRequest) -> SampleFrame: ...
    def input_source(self, port: str) -> tuple[str, str] | None: ...
    def mode_is(self, key: str, value: Any = None) -> bool: ...
    def mode_path(self) -> str | None: ...

    name: Any

    #: The instrument the component sits in — identity only (the recorder's acquisition event is
    #: emitted with it as the subject): no state or service is read through it (#1724).
    owner: Instrument | None

    @property
    def on_panel(self) -> bool: ...
    def now_ns(self) -> int: ...
    def opc_query(self) -> tuple[bytes | None, int]: ...
    def param(self, key: str) -> Any: ...

    recorder: Recorder

    def resolve_path(self, path: str) -> str: ...
    def sample_rate(self) -> float: ...
    def scale_offset(self, n: int) -> tuple[float, float]: ...

    segments: Segments
    session: Session

    def set_mode(self, value: str) -> None: ...
    def set_state(self, path: str, value: Any) -> None: ...
    def status_event(self, name: str) -> None: ...
    def timing(self) -> tuple[int, float, int, int]: ...
    def trigger_level(self) -> float: ...
    def trigger_unit(self) -> Any: ...  # ScopeTrigger (ty reads a @component class as a variable)
    @property
    def uid(self) -> str: ...
    def vertical_of(self, n: int) -> Any: ...  # ScopeVertical (ty reads a @component class as a variable)
    def wait_pending(self) -> int: ...
    def wait_until(self, done_ns: int) -> int: ...
    def warn(self, code: str, message: str) -> None: ...

    runner: RunControl
