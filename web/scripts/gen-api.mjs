// Generate the web client's interface types from the schemas exported by `simubench schemas` (D21).
// Usage: node scripts/gen-api.mjs [--check]   (--check fails when the committed output is stale)
import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";
import { compile } from "json-schema-to-typescript";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..", "..");
const schemas = path.join(root, "schemas");
const outDir = path.resolve(here, "..", "src", "api", "generated");
const check = process.argv.includes("--check");

const banner = "// Generated by web/scripts/gen-api.mjs from /schemas. Do not edit by hand.\n\n";

async function generate() {
  const openapi = JSON.parse(await readFile(path.join(schemas, "openapi.json"), "utf8"));
  const ast = await openapiTS(openapi, { alphabetize: true });
  const files = { "openapi.ts": banner + astToString(ast) };
  for (const [name, title] of [
    ["events.schema.json", "Event"],
    ["bench.schema.json", "BenchDefinition"],
  ]) {
    const schema = JSON.parse(await readFile(path.join(schemas, name), "utf8"));
    const ts = await compile(schema, title, { bannerComment: "", additionalProperties: false, style: { singleQuote: false } });
    files[name.replace(".schema.json", ".ts")] = banner + ts;
  }
  return files;
}

const files = await generate();
let stale = [];
for (const [name, content] of Object.entries(files)) {
  const target = path.join(outDir, name);
  if (check) {
    const current = await readFile(target, "utf8").catch(() => "");
    if (current !== content) stale.push(name);
  } else {
    await mkdir(outDir, { recursive: true });
    await writeFile(target, content);
    console.log("wrote", path.relative(root, target));
  }
}
if (check && stale.length) {
  console.error(`Generated interface files are stale: ${stale.join(", ")}. Run: pnpm gen:api`);
  process.exit(1);
}
